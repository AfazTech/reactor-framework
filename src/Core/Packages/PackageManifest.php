<?php

namespace Reactor\Core\Packages;

use Reactor\Contracts\LoggerInterface;
use Reactor\Core\Paths;

/**
 * Reads the Composer installed packages and extracts Reactor package metadata.
 *
 * Performance in webhook mode:
 *   - When `app.debug` is false (production), the cache staleness check is
 *     skipped entirely. The manifest is assumed to be up to date because
 *     `composer install` / `composer update` regenerate it via the
 *     `package:discover` post-autoload hook. This removes two `filemtime()`
 *     syscalls from every webhook request.
 *   - When `app.debug` is true (development), the staleness check is kept
 *     so that editing a package's composer.json is picked up immediately.
 *   - APCu is used, when available, to cache the staleness result for a
 *     short interval in development, further reducing syscalls.
 */
class PackageManifest
{
    private const STALENESS_CACHE_KEY = 'reactor:manifest_stale';
    private const STALENESS_TTL = 5;

    private array $packages = [];
    private string $manifestPath;
    private string $installedPath;
    private ?LoggerInterface $logger;
    private bool $debugMode;

    public function __construct(
        private Paths $paths,
        private string $vendorPath,
        ?LoggerInterface $logger = null,
        bool $debugMode = false,
    ) {
        $this->logger = $logger;
        $this->debugMode = $debugMode;
        $this->manifestPath = $paths->path('bootstrap/cache/packages.php');
        $this->installedPath = rtrim($vendorPath, '/') . '/composer/installed.json';

        $this->load();
    }

    private function load(): void
    {
        if ($this->canUseCache()) {
            $data = $this->readCache();
            if ($data !== null) {
                $this->packages = $data;
                return;
            }
        }

        $this->packages = $this->scan();
        $this->write();
    }

    private function canUseCache(): bool
    {
        if (!file_exists($this->manifestPath)) {
            return false;
        }

        // Production: trust the manifest. It is regenerated by composer
        // hooks on deploy, so checking mtime on every webhook request is
        // unnecessary overhead.
        if (!$this->debugMode) {
            return true;
        }

        // Development: check whether the manifest is stale, with APCu
        // caching to avoid two filemtime() syscalls per request.
        return !$this->isStale();
    }

    private function readCache(): ?array
    {
        try {
            $data = require $this->manifestPath;
        } catch (\Throwable $e) {
            $this->logger?->warning('Package manifest cache is unreadable, rebuilding', [
                'path'  => $this->manifestPath,
                'error' => $e->getMessage(),
            ]);
            return null;
        }

        if (!is_array($data)) {
            return null;
        }

        return array_values(array_filter($data, 'is_array'));
    }

    private function isStale(): bool
    {
        $cached = $this->readStalenessFromCache();
        if ($cached !== null) {
            return $cached;
        }

        $stale = !file_exists($this->installedPath)
            || filemtime($this->manifestPath) < filemtime($this->installedPath);

        $this->writeStalenessToCache($stale);

        return $stale;
    }

    private function readStalenessFromCache(): ?bool
    {
        if (!function_exists('apcu_fetch')) {
            return null;
        }

        $success = false;
        $value = apcu_fetch(self::STALENESS_CACHE_KEY, $success);

        return $success ? (bool) $value : null;
    }

    private function writeStalenessToCache(bool $stale): void
    {
        if (function_exists('apcu_store')) {
            apcu_store(self::STALENESS_CACHE_KEY, $stale, self::STALENESS_TTL);
        }
    }

    /**
     * Scan vendor/composer/installed.json for Reactor packages.
     *
     * @return array<int, array<string, mixed>>
     */
    private function scan(): array
    {
        if (!file_exists($this->installedPath)) {
            return [];
        }

        $raw = file_get_contents($this->installedPath);
        if ($raw === false) {
            return [];
        }

        $decoded = json_decode($raw, true);
        if (!is_array($decoded)) {
            return [];
        }

        $list = $decoded['packages'] ?? $decoded;
        if (!is_array($list)) {
            return [];
        }

        $packages = [];

        foreach ($list as $entry) {
            if (!is_array($entry)) {
                continue;
            }
            if (($entry['type'] ?? '') !== 'reactor-package') {
                continue;
            }

            $name = (string) ($entry['name'] ?? '');
            if ($name === '') {
                continue;
            }

            $extra = $entry['extra']['reactor'] ?? [];
            if (!is_array($extra)) {
                $extra = [];
            }

            $installPath = rtrim($this->vendorPath, '/') . '/' . $name;
            $configPath = $installPath . '/config';
            $migrationsPath = $installPath . '/database/migrations';

            $packages[] = [
                'name'                 => $name,
                'path'                 => $installPath,
                'providers'            => $this->normalizeStringList($extra['providers'] ?? []),
                'aliases'              => $this->normalizeAssoc($extra['aliases'] ?? []),
                'migrations_namespace' => (string) ($extra['migrations_namespace'] ?? ''),
                'config_path'          => is_dir($configPath) ? $configPath : null,
                'migrations_path'      => is_dir($migrationsPath) ? $migrationsPath : null,
            ];
        }

        return $packages;
    }

    /**
     * @return array<int, string>
     */
    private function normalizeStringList(mixed $value): array
    {
        if (!is_array($value)) {
            return [];
        }
        return array_values(array_filter($value, 'is_string'));
    }

    /**
     * @return array<string, string>
     */
    private function normalizeAssoc(mixed $value): array
    {
        if (!is_array($value)) {
            return [];
        }
        $result = [];
        foreach ($value as $key => $item) {
            if (is_string($key) && is_string($item) && $key !== '' && $item !== '') {
                $result[$key] = $item;
            }
        }
        return $result;
    }

    private function write(): void
    {
        $dir = dirname($this->manifestPath);
        if (!is_dir($dir)) {
            @mkdir($dir, 0755, true);
        }

        $export = var_export($this->packages, true);
        $content = "<?php\n\n// Auto-generated by Reactor PackageManifest. Do not edit.\n\nreturn " . $export . ";\n";

        if (@file_put_contents($this->manifestPath, $content) === false) {
            $this->logger?->warning('Could not write package manifest cache', [
                'path' => $this->manifestPath,
            ]);
            return;
        }

        $this->logger?->debug('Package manifest written', [
            'path'  => $this->manifestPath,
            'count' => count($this->packages),
        ]);
    }

    /**
     * Force a rebuild of the cached package manifest.
     */
    public function rebuild(): void
    {
        if (file_exists($this->manifestPath)) {
            @unlink($this->manifestPath);
        }
        $this->packages = $this->scan();
        $this->write();

        if (function_exists('apcu_delete')) {
            apcu_delete(self::STALENESS_CACHE_KEY);
        }
    }

    /**
     * @return array<int, array<string, mixed>>
     */
    public function all(): array
    {
        return $this->packages;
    }

    public function hasAny(): bool
    {
        return $this->packages !== [];
    }

    public function manifestPath(): string
    {
        return $this->manifestPath;
    }
}
